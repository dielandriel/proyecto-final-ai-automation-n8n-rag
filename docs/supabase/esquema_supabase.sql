-- Estructura de Supabase para el Vector Store del prototipo
--
-- Script de referencia para reproducir la estructura verificada en el proyecto de pruebas
-- (tabla, función, dimensión, permisos y RLS; ver docs/REGISTRO_PRUEBAS_PASO_17.md, Prueba 3).
-- No es una copia del script ejecutado originalmente y no se probó sobre un proyecto nuevo:
-- revisar el resultado con las verificaciones del final antes de ejecutar WF-01.
--
-- Requisitos:
-- - Embeddings Google Gemini en n8n con gemini-embedding-001 (vectores de 3072 dimensiones).
-- - La credencial "Supabase API" de n8n usa la URL del proyecto y la clave de servicio (service_role).

-- 1. Extensión pgvector en el esquema extensions
create extension if not exists vector with schema extensions;

-- 2. Tabla de fragmentos
create table if not exists public.documents (
  id bigint generated by default as identity primary key,
  content text,
  metadata jsonb,
  embedding extensions.vector(3072)
);

-- Sin índice vectorial: con menos de 100 fragmentos la búsqueda secuencial es suficiente.

-- 3. Seguridad: RLS activado, sin políticas; solo el rol de servicio accede
alter table public.documents enable row level security;

revoke all on table public.documents from anon, authenticated;
grant select, insert, delete on table public.documents to service_role;
grant usage on sequence public.documents_id_seq to service_role;

-- 4. Función de búsqueda por similitud coseno (la usan los nodos Supabase Vector Store)
create or replace function public.match_documents (
  query_embedding extensions.vector(3072),
  match_count int default null,
  filter jsonb default '{}'
)
returns table (
  id bigint,
  content text,
  metadata jsonb,
  similarity float
)
language plpgsql
set search_path = ''
as $$
begin
  return query
  select
    d.id,
    d.content,
    d.metadata,
    1 - (d.embedding operator(extensions.<=>) query_embedding) as similarity
  from public.documents d
  where d.metadata @> filter
  order by d.embedding operator(extensions.<=>) query_embedding
  limit match_count;
end;
$$;

revoke execute on function public.match_documents(extensions.vector, int, jsonb) from public, anon, authenticated;
grant execute on function public.match_documents(extensions.vector, int, jsonb) to service_role;

